function write(rows: Row[], file: string) {
  const sheet = XLSX.utils.aoa_to_sheet([questionTemplateHeaders(), ...rows.map((r, i) => [i + 1, ...r])]);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, sheet, "문제");
  XLSX.writeFile(wb, file);
  console.log(`wrote ${file} (${rows.length} rows)`);
}

